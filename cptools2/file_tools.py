"""
file_tools.py - File handling utilities for cptools2

This module extends cptools2 with capabilities for post-processing analysis
results generated by CellProfiler pipelines. The main functionality involves
automatically joining CSV output files based on patterns specified in the
configuration YAML file, with automatic metadata enrichment from LoadData files.

Key features:
- Automatically enriches output files with LoadData metadata before concatenation
- Combines output files across chunked jobs for each plate
- Supports multiple file patterns (e.g., "Image.csv", "Cells.csv")
- Creates organized output in a dedicated "joined_files" directory
- Provides detailed logging of the joining process
- Integrates with the cptools2 workflow configuration

These tools are especially useful in high-throughput image analysis workflows
where each plate's data might be spread across multiple output files due to
the chunking process. Rather than manually combining these files after analysis,
this module automates the process based on the original experiment structure.

Usage in YAML configuration:
```
join_files: ["Image.csv", "Cells.csv"]  # Join multiple file types
```
or
```
join_files: "Image.csv"  # Join a single file type
```

If no joining is required, simply omit the join_files parameter.
"""

import glob
import os

import pandas as pd

from cptools2.colours import pretty_print, purple, red, yellow


def merge_loaddata_metadata(chunk_output_csv, loaddata_csv, output_path=None):
    """
    Merge LoadData metadata into CellProfiler output CSV using an index-based join.

    This function adds a 1-based ImageNumber index to the LoadData CSV and joins
    it with the CellProfiler output CSV. This approach mimics R's bind_cols
    for Image.csv while correctly broadcasting metadata for Cells.csv.

    Parameters
    ----------
    chunk_output_csv : str
        Path to the CellProfiler output CSV file.
    loaddata_csv : str
        Path to the corresponding LoadData CSV file.
    output_path : str, optional
        Path to write the enriched CSV. If None, overwrites in-place.

    Returns
    -------
    dict
        Success status and metadata details.
    """
    result = {
        "success": False,
        "output_file": output_path or chunk_output_csv,
        "rows_before": 0,
        "rows_after": 0,
        "metadata_columns_added": [],
        "null_metadata_count": 0,
        "error": None,
    }
    try:
        # Load data
        out_df = pd.read_csv(chunk_output_csv, low_memory=False)
        load_df = pd.read_csv(loaddata_csv, low_memory=False)

        result["rows_before"] = len(out_df)

        # Create 1-based ImageNumber index on LoadData
        # (This matches CellProfiler's internal assignment for chunks)
        load_df["ImageNumber"] = range(1, len(load_df) + 1)

        # Identify missing columns to add (exclude existing ones)
        new_cols = [c for c in load_df.columns if c not in out_df.columns]
        result["metadata_columns_added"] = new_cols

        if not new_cols:
            result["success"] = True
            result["rows_after"] = len(out_df)
            return result

        # Join on ImageNumber
        enriched_df = out_df.merge(
            load_df[["ImageNumber"] + new_cols], on="ImageNumber", how="left"
        )

        # Count nulls for reporting
        result["null_metadata_count"] = enriched_df[new_cols].isna().sum().sum()

        # Save
        target = output_path or chunk_output_csv
        enriched_df.to_csv(target, index=False, encoding="utf-8-sig")

        result["rows_after"] = len(enriched_df)
        result["success"] = True
        return result

    except Exception as e:
        pretty_print(f"Error merging metadata: {red(str(e))}")
        result["error"] = str(e)
        return result


def _discover_chunks_for_plate(raw_data_location, plate_name):
    """
    Discover all chunk directories for a given plate.

    Parameters
    ----------
    raw_data_location : str
        Path to raw_data directory
    plate_name : str
        Plate name (e.g., 'plateName')

    Returns
    -------
    list
        Sorted list of chunk directory paths matching pattern plateName_*
    """
    chunks = []
    try:
        for item in os.listdir(raw_data_location):
            if item.startswith(f"{plate_name}_"):
                chunk_path = os.path.join(raw_data_location, item)
                if os.path.isdir(chunk_path):
                    chunks.append(chunk_path)
    except FileNotFoundError:
        pass
    return sorted(chunks)


def _discover_plates_from_raw_data(raw_data_location):
    """Discover plate names by examining directory structure in raw_data."""
    plate_names = set()
    try:
        # Look for directories like 'plateName_chunkNum' inside raw_data_location
        for item in os.listdir(raw_data_location):
            item_path = os.path.join(raw_data_location, item)
            if os.path.isdir(item_path) and "_" in item:
                # Split from right to avoid truncating plate names with underscores
                # Expected format: "<plate_name>_<job_or_chunk_id>"
                plate_name = item.rsplit("_", 1)[0]
                plate_names.add(plate_name)
    except FileNotFoundError:
        pretty_print(
            "Warning: Raw data location "
            f"{raw_data_location} not found during plate discovery."
        )
        return []
    if not plate_names:
        pretty_print(
            "Warning: No plate directories found in "
            f"{raw_data_location}. Cannot join files."
        )
    return sorted(list(plate_names))


def enrich_chunks_with_metadata(location, patterns=None):
    """
    Enrich all chunks with LoadData metadata before concatenation.

    This function discovers all chunk/LoadData pairs and merges metadata into
    each chunk's output CSVs. This MUST happen before concatenation to
    preserve ImageNumber integrity.
    """
    results = {
        "total_chunks_processed": 0,
        "total_files_enriched": 0,
        "errors": [],
    }
    raw_data_location = os.path.join(location, "raw_data")
    loaddata_location = os.path.join(location, "loaddata")

    if not os.path.exists(raw_data_location) or not os.path.exists(
        loaddata_location
    ):
        pretty_print("Metadata enrichment skipped (directories missing)")
        return results

    pretty_print("PHASE 1: Starting metadata enrichment...")

    plate_names = _discover_plates_from_raw_data(raw_data_location)

    for plate in plate_names:
        chunks = _discover_chunks_for_plate(raw_data_location, plate)
        for chunk_path in chunks:
            chunk_name = os.path.basename(chunk_path)
            loaddata_csv = os.path.join(loaddata_location, f"{chunk_name}.csv")

            if not os.path.exists(loaddata_csv):
                results["errors"].append(f"Missing loaddata: {chunk_name}")
                continue

            # Find files to enrich
            csv_files = []
            if patterns:
                for p in patterns:
                    csv_files.extend(glob.glob(os.path.join(chunk_path, p)))
            else:
                csv_files = glob.glob(os.path.join(chunk_path, "*.csv"))

            enriched_in_chunk = 0
            for csv_file in csv_files:
                res = merge_loaddata_metadata(csv_file, loaddata_csv)
                if res.get("success"):
                    results["total_files_enriched"] += 1
                    enriched_in_chunk += 1
                else:
                    results["errors"].append(f"Merge error in {csv_file}")

            if enriched_in_chunk > 0:
                results["total_chunks_processed"] += 1

    pretty_print(
        f"Metadata enrichment complete! Enriched {results['total_files_enriched']} files."
    )
    return results


def _concatenate_and_save_files(
    matched_files,
    plate_name,
    pattern,
    raw_data_location,
    batch_id,
    enrich_metadata,
    results,
):
    """Concatenate and save matched CSV files for a plate and pattern."""
    try:
        combined_csv = pd.concat(
            [pd.read_csv(f, low_memory=False) for f in matched_files]
        )

        # Determine output directory
        parent_dir = os.path.dirname(raw_data_location)
        output_dir_name = (
            f"joined_files_batch_{batch_id}"
            if batch_id is not None
            else "joined_files"
        )
        output_dir = os.path.join(parent_dir, output_dir_name)
        os.makedirs(output_dir, exist_ok=True)
        output_file = os.path.join(output_dir, f"{plate_name}_{pattern}")

        combined_csv.to_csv(output_file, index=False, encoding="utf-8-sig")

        # Store output info
        if plate_name not in results:
            results[plate_name] = {}
        results[plate_name][pattern] = {
            "output_file": output_file,
            "rows": len(combined_csv),
            "files_combined": len(matched_files),
            "metadata_enriched": enrich_metadata,
        }

        pretty_print(
            f"\tCreated {yellow(output_file)} with "
            f"{purple(len(combined_csv))} rows from "
            f"{purple(len(matched_files))} files"
        )
    except Exception as e:
        pretty_print(
            f"\tError processing pattern {yellow(pattern)} "
            f"for plate {purple(plate_name)}: {str(e)}"
        )


def join_plate_files(
    plate_store,
    raw_data_location,
    patterns=None,
    batch_id=None,
    enrich_metadata=True,
):
    """
    Join result files for each plate based on specified patterns.

    IMPORTANT: Metadata enrichment happens BEFORE concatenation. This is
    critical because ImageNumber is sequential within each chunk (1-96,
    1-96, ...) and resets per chunk. If we concatenate first, ImageNumber
    loses meaning. By enriching each chunk individually before concatenation,
    we preserve metadata integrity.

    If plate_store is None, attempts to discover plate names from the
    directory structure within raw_data_location.

    Parameters
    ----------
    plate_store : dict or None
        Dictionary of plates from Job.plate_store, or None to discover plates.
    raw_data_location : string
        Path to where raw data (chunked directories like 'plateName_chunkNum')
        is stored.
    patterns : list or None
        List of file patterns to join (e.g., ["Image.csv", "Cells.csv"])
        If None, no files will be joined.
    batch_id : int or None
        Optional identifier for the batch, used to create a unique output
        directory.
    enrich_metadata : bool (default=True)
        Whether to enrich chunks with LoadData metadata before concatenation.

    Returns
    -------
    dict or None
        Dictionary with joined file information, or None if no patterns.
    """
    if not patterns:
        pretty_print("No file joining patterns specified. Skipping file joining.")
        return None

    # PHASE 1: ENRICH chunks with metadata BEFORE concatenation
    if enrich_metadata:
        location = os.path.dirname(raw_data_location)
        enrich_chunks_with_metadata(location, patterns)

    # PHASE 2: Concatenate enriched chunks
    pretty_print("PHASE 2: Concatenating enriched chunks...")
    pretty_print(
        "Joining files with patterns: {}".format(
            ", ".join([yellow(pattern) for pattern in patterns])
        )
    )

    results = {}

    # Determine plate names
    if plate_store:
        plate_names = sorted(plate_store.keys())
        pretty_print(
            f"Using plate names from provided plate_store: "
            f"{len(plate_names)}"
        )
    else:
        pretty_print(
            f"No plate_store provided. Discovering plates from: "
            f"{raw_data_location}"
        )
        plate_names = _discover_plates_from_raw_data(raw_data_location)
        if not plate_names:
            return None
        pretty_print(
            f"Discovered plate names: {', '.join(purple(p) for p in plate_names)}"
        )

    for pattern in patterns:
        pretty_print("Processing pattern: {}".format(yellow(pattern)))

        for plate_name in plate_names:
            pretty_print(
                "\tProcessing plate: {}".format(purple(plate_name))
            )

            search_pattern = os.path.join(
                raw_data_location, f"{plate_name}_*", pattern
            )
            matched_files = glob.glob(search_pattern)

            if not matched_files:
                pretty_print(
                    f"\tNo files found for plate {purple(plate_name)} "
                    f"with pattern {yellow(pattern)}"
                )
                continue

            _concatenate_and_save_files(
                matched_files,
                plate_name,
                pattern,
                raw_data_location,
                batch_id,
                enrich_metadata,
                results,
            )

    return results
